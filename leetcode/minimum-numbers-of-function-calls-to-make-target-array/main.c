int isZeros(const int *nums, const int numsSize) {
  for (int i = 0; i < numsSize; ++i) {
    if (nums[i] != 0) {
      return 0;
    }
  }

  return 1;
}

int minOperations(int *nums, int numsSize) {
  int iterations = 0;
  while (!isZeros(nums, numsSize)) {
    int subtractions = 0;
    for (int i = 0; i < numsSize; ++i) {
      if (nums[i] % 2 != 0) {
        --nums[i];
        ++subtractions;
        ++iterations;
      }
    }

    if (subtractions == 0) {
      for (int i = 0; i < numsSize; ++i) {
        nums[i] /= 2;
      }
      ++iterations;
    }
  }

  return iterations;
}

